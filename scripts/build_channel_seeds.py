"""Consolidate the three verified channel lists into one seed table.

Reads verified bronze data (real channel_id/handle/subscriber counts from Supadata
and yt-dlp) and applies the keep/cut/domain/tier decisions made across three rounds
of review. One-time build step, not part of the ingest pipeline — its output,
seeds/youtube_channels.yaml, is what ingestion (step 3) actually reads.

Re-run after a fresh channel survey; domain and authority_tier are meant to be
hand-tuned in the YAML afterward, so a re-run should be reviewed as a diff, not
applied blindly.
"""

