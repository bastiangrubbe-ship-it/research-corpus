    roles = ", ".join(POLICY_ROLES)
    for table in tables:
        for stmt in enable_rls_sql(table):
            op.execute(stmt)
        op.execute(f"GRANT SELECT, INSERT, UPDATE, DELETE ON {table} TO {roles}")

    # The tenant table itself is not tenant-scoped, but the application roles need
    # to read it to resolve a slug to an id.
    op.execute(f"GRANT SELECT ON tenant TO {roles}")


